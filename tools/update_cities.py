def normalise(name: str) -> str:
    return name.strip().lower().replace("ё", "е")


def probe(fetcher: Fetcher, name: str) -> tuple[str, str] | None:
    """Возвращает (alias, region_id) для города или None, если ни один вариант не подошёл."""
    for alias in (*EXTRA_ALIASES.get(name, ()), *alias_candidates(name)):
        try:
            state = parse_state(fetcher.get(f"{SITE}/{alias}"))
        except FetchError:
            continue
        title, region_id = region_info(state)
        if title and normalise(title) == normalise(name):
            return alias, region_id
    return None


def main() -> int:
    wanted = sys.argv[1:]
    names = [(n, r) for n, r in CITIES if not wanted or n in wanted]
    if wanted:
        known = {n for n, _ in CITIES}
        names += [(n, "") for n in wanted if n not in known]

    existing: dict[str, dict[str, str]] = {}
    if DATA_FILE.exists():
        raw = json.loads(DATA_FILE.read_text(encoding="utf-8"))
        existing = {normalise(c["name"]): c for c in raw.get("cities", [])}

    found = 0
    with Fetcher(delay=1.0, log=lambda message: print("   ", message)) as fetcher:
        for name, region in names:
            result = probe(fetcher, name)
            if result:
                alias, region_id = result
                existing[normalise(name)] = {
                    "name": name,
                    "alias": alias,
                    "region": region,
                    "region_id": region_id,
                }
                found += 1
                print(f"  {name:<28} → {alias}")
            else:
                print(f"  {name:<28} → не найден в 2ГИС")

    DATA_FILE.parent.mkdir(parents=True, exist_ok=True)
    payload = {"cities": sorted(existing.values(), key=lambda c: c["name"])}
    DATA_FILE.write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\nВ справочнике {len(existing)} городов, в этот раз подтвердилось {found}.")
    print(f"Файл: {DATA_FILE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
