def main() -> int:
    TEMPLATES.mkdir(parents=True, exist_ok=True)
    written = 0
    for name, queries, note in NICHES:
        if any(not query.isprintable() or not query.strip() for query in queries):
            print(f"пропускаю {name}: в запросах мусор", file=sys.stderr)
            continue
        lines = [f'name = "{name}"', "queries = ["]
        lines += [f'    "{query}",' for query in queries]
        lines.append("]")
        if note:
            lines.append(f'note = "{note}"')
        path = TEMPLATES / f"{name}.toml"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        written += 1
    print(f"Ниш записано: {written} → {TEMPLATES}")
    return 0


